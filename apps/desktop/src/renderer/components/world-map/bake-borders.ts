/**
 * Author-time bake for the 1880 political borders of the playable nations.
 *
 * Reads one file — `world_1880.geojson` from aourednik/historical-basemaps
 * (https://github.com/aourednik/historical-basemaps, GPL-3.0; its own caveat is
 * that the maps are "work in progress" and borders at world scale) — keeps the
 * features that belong to a playable nation (the nation itself plus the
 * territories it held), simplifies them, and writes `borders-1880-data.ts`.
 * Nothing is fetched at runtime and nothing is added to package.json.
 *
 * Run (the GeoJSON is untrusted input: pass it by path, from a directory of its own):
 *   node apps/desktop/src/renderer/components/world-map/bake-borders.ts /path/to/world_1880.geojson
 *
 * See docs/adr/ for the provenance and licensing note that goes with this data.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/** Playable campaign nation id -> dataset features to include (by SUBJECTO or NAME). */
const NATIONS: Readonly<Record<string, { subjects: string[]; names?: string[] }>> = {
  uk: {
    subjects: ["United Kingdom of Great Britain and Ireland", "United Kingdom", "Great Britain"],
  },
  france: { subjects: ["France"] },
  germany: { subjects: ["Germany"] },
  italy: { subjects: ["Italy"] },
  spain: { subjects: ["Spain"] },
  russia: { subjects: ["Russian Empire"] },
  austria_hungary: { subjects: ["Austria Hungary"] },
  usa: { subjects: ["United States of America"] },
  japan: { subjects: ["Imperial Japan"] },
  qing: { subjects: ["Manchu Empire"], names: ["Taiwan"] },
};

/** Degrees. The source is already coarse; this only drops collinear noise. */
const TOLERANCE = 0.05;

type Ring = number[];

function perpendicular(px: number, py: number, ax: number, ay: number, bx: number, by: number) {
  const dx = bx - ax;
  const dy = by - ay;
  const length = dx * dx + dy * dy;
  if (length === 0) return Math.hypot(px - ax, py - ay);
  const t = Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / length));
  return Math.hypot(px - (ax + t * dx), py - (ay + t * dy));
}

/** Douglas–Peucker over a flat [lon, lat, …] ring. */
function simplify(ring: Ring, tolerance: number): Ring {
  const count = ring.length / 2;
  if (count <= 4) return ring;
  const keep = new Uint8Array(count);
  keep[0] = 1;
  keep[count - 1] = 1;
  const stack: [number, number][] = [[0, count - 1]];
  while (stack.length > 0) {
    const [from, to] = stack.pop() as [number, number];
    let worst = 0;
    let index = -1;
    for (let i = from + 1; i < to; i++) {
      const d = perpendicular(
        ring[i * 2] as number,
        ring[i * 2 + 1] as number,
        ring[from * 2] as number,
        ring[from * 2 + 1] as number,
        ring[to * 2] as number,
        ring[to * 2 + 1] as number,
      );
      if (d > worst) {
        worst = d;
        index = i;
      }
    }
    if (index !== -1 && worst > tolerance) {
      keep[index] = 1;
      stack.push([from, index], [index, to]);
    }
  }
  const out: Ring = [];
  for (let i = 0; i < count; i++) {
    if (keep[i] === 1) out.push(ring[i * 2] as number, ring[i * 2 + 1] as number);
  }
  return out.length >= 6 ? out : ring;
}

interface Feature {
  properties: { NAME: string; SUBJECTO: string };
  geometry: { type: string; coordinates: unknown };
}

const source = process.argv[2];
if (source === undefined) throw new Error("usage: bake-borders.ts /path/to/world_1880.geojson");
const collection = JSON.parse(readFileSync(source, "utf8")) as { features: Feature[] };

const round = (value: number) => Math.round(value * 100) / 100;
const result: Record<string, Ring[][]> = {};

for (const [nation, rule] of Object.entries(NATIONS)) {
  const polygons: Ring[][] = [];
  for (const feature of collection.features) {
    const { NAME, SUBJECTO } = feature.properties;
    if (!rule.subjects.includes(SUBJECTO) && !(rule.names ?? []).includes(NAME)) continue;
    const geometry = feature.geometry;
    const parts =
      geometry.type === "MultiPolygon"
        ? (geometry.coordinates as number[][][][])
        : geometry.type === "Polygon"
          ? [geometry.coordinates as number[][][]]
          : [];
    for (const part of parts) {
      const rings: Ring[] = [];
      for (const ring of part) {
        const flat = simplify(
          ring.flatMap(([lon, lat]) => [lon as number, lat as number]),
          TOLERANCE,
        );
        rings.push(flat.map(round));
      }
      polygons.push(rings);
    }
  }
  if (polygons.length === 0) throw new Error(`no features matched for ${nation}`);
  result[nation] = polygons;
}

const here = dirname(fileURLToPath(import.meta.url));
const header = `/**
 * GENERATED by bake-borders.ts — do not edit.
 *
 * 1880 borders of the playable nations (and the territories each held), as flat
 * [lon, lat, …] rings. Source: aourednik/historical-basemaps, world_1880.geojson
 * (GPL-3.0; approximate, world-scale). Presentation only: the engine never reads it.
 */

import type { FlatPolygon } from "../../lib/simplify-geometry.js";

export const BORDERS_1880: Readonly<Record<string, readonly FlatPolygon[]>> = `;
writeFileSync(join(here, "borders-1880-data.ts"), `${header}${JSON.stringify(result)};\n`);
const total = Object.values(result).reduce(
  (n, polys) => n + polys.reduce((m, p) => m + p.reduce((k, r) => k + r.length / 2, 0), 0),
  0,
);
console.log(`wrote borders-1880-data.ts: ${Object.keys(result).length} nations, ${total} points`);
