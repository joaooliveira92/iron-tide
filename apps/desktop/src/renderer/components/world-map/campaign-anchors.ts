export function areaAnchor(areaId: string): LonLat | null {
  return AREA_ANCHORS[areaId] ?? null;
}

export function portAnchor(portId: string, areaId: string): LonLat | null {
  return PORT_ANCHORS[portId] ?? areaAnchor(areaId);
}

export function lanePath(
  routeId: string,
  fromArea: string,
  toArea: string,
): readonly LonLat[] | null {
  const from = areaAnchor(fromArea);
  const to = areaAnchor(toArea);
  if (from === null || to === null) return null;
  return [from, ...(LANE_WAYPOINTS[routeId] ?? []), to];
}
