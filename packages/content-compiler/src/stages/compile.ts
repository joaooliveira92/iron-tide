import { canonicalSerialize, sha256Hex } from "@bluewave/deterministic";
import type { DiagnosticCollector } from "@bluewave/diagnostics";
import type {
  Area,
  ContentPack,
  Nation,
  PackManifest,
  Port,
  Possession,
  PresentationContent,
  RouteEdge,
  RulesetManifest,
  TechnologyPrerequisite,
} from "@bluewave/content-schema";

import type {
  CampaignCollections,
  CompilerOutput,
  CompilerStage,
  ContentBundle,
  ShipBuildingCatalogue,
} from "../index.js";
import type { NormalizeOutput } from "./normalize.js";

/** The do-not-edit marker carried by every generated bundle (BW-RUL-002, DESIGN-05). */
export const BUNDLE_GENERATED_BY =
  "Generated by `bwc content:build`. Do not edit by hand; rebuild from authored content.";

/**
 * The raw content-pack subset shape — exactly what `bwc compile` serializes and
 * the `CompilerOutput.pack` wire format. Reconstructing it from a bundle is the
 * one place the compiler's `ContentPack` view is asserted; the schema's declared
 * shape (`technologyChains`) does not match the compiled artifact, whose
 * technology collection is `technologies` (unused by runtime consumers).
 */
export interface ContentPackArtifact {
  manifest: unknown;
  rulesets: unknown[];
  nations: unknown[];
  areas: unknown[];
  routes: unknown[];
  possessions: unknown[];
  ports: unknown[];
  technologies: unknown[];
}

/**
 * Presents a content-pack artifact as the runtime `ContentPack` view. The
 * artifact's collections are re-typed here (not `as unknown`); the artifact
 * boundary (`verifyContentBundleArtifact`) is where a bundle is decoded through
 * the schemas, so this view is built from already-decoded collections.
 */
export function contentPackFromArtifact(artifact: ContentPackArtifact): ContentPack {
  return {
    manifest: artifact.manifest as PackManifest,
    rulesets: artifact.rulesets as RulesetManifest[],
    nations: artifact.nations as Nation[],
    areas: artifact.areas as Area[],
    routes: artifact.routes as RouteEdge[],
    possessions: artifact.possessions as Possession[],
    ports: artifact.ports as Port[],
    technologies: artifact.technologies as TechnologyPrerequisite[],
  };
}

/**
 * The manifest identity recorded in the compiled artifact: the pack's `name`,
 * `version`, `type` and its content-pack/campaign `files` declaration. The
 * build-only `shipBuilding` loading declaration is excluded so the manifest
 * authority is hash-neutral (CAH-MAN-1): declaring which ship-building files to
 * load does not change the artifact body hash. The declaration is still
 * validated and enforced by `buildFullSurfaceInput`.
 */
function artifactManifest(manifest: unknown): unknown {
  if (typeof manifest !== "object" || manifest === null || Array.isArray(manifest)) {
    return manifest;
  }
  const { shipBuilding: _shipBuilding, ...identity } = manifest as Record<string, unknown>;
  return identity;
}

export class CompileStage implements CompilerStage<NormalizeOutput, CompilerOutput> {
  readonly name = "compile";

  run(
    input: NormalizeOutput,
    _signal: AbortSignal,
    _collector: DiagnosticCollector,
  ): CompilerOutput {
    const artifact = {
      manifest: artifactManifest(input.manifest),
      rulesets: input.rulesets,
      nations: input.countries,
      areas: input.areas,
      routes: input.routes,
      possessions: input.possessions,
      ports: input.ports,
      technologies: input.technologies,
    };

    const rawJson = canonicalSerialize(artifact);
    const rawHash = sha256Hex(rawJson);

    const envelope = {
      algorithm: "sha256",
      artifactKind: "content-pack",
      compatibilityVersion: "0.1.0",
      bodyHash: rawHash,
      bodyLength: Buffer.byteLength(rawJson, "utf8"),
    };

    const envelopeJson = canonicalSerialize(envelope);
    const envelopeHash = sha256Hex(envelopeJson);

    const shipBuilding = buildShipBuildingCatalogue(input);
    const campaign = buildCampaignCollections(input);
    const bundle: ContentBundle = {
      generatedBy: BUNDLE_GENERATED_BY,
      ...artifact,
      ...(shipBuilding !== undefined ? { shipBuilding } : {}),
      ...(campaign !== undefined ? { campaign } : {}),
      ...(input.presentation !== undefined
        ? { presentation: input.presentation as PresentationContent }
        : {}),
    };

    const manifestVersion = (input.manifest as { version?: unknown } | undefined)?.version;

    return {
      pack: contentPackFromArtifact(artifact),
      rawHash,
      envelopeHash,
      bundle,
      contentVersion: typeof manifestVersion === "string" ? manifestVersion : "0.0.0",
    };
  }
}

/**
 * Builds the ship-building catalogue section of the bundle, or `undefined` when
 * the input carried no ship-building content (a content-pack-only build). The
 * shape matches `ShipBuildingData` (minus `technologies`, which is a bundle-root
 * collection), so the runtime can hand it to `buildShipBuildingContent` directly.
 */
function buildShipBuildingCatalogue(input: NormalizeOutput): ShipBuildingCatalogue | undefined {
  const hasCatalogue =
    input.shipBalance !== undefined ||
    input.shipComponents.length > 0 ||
    input.propulsionPlants.length > 0 ||
    input.shipHullForms.length > 0 ||
    input.gunFamilies.length > 0 ||
    input.gunModels.length > 0 ||
    input.gunMounts.length > 0 ||
    input.ammunition.length > 0 ||
    input.navalProfiles.length > 0 ||
    input.referenceDesigns.length > 0 ||
    input.designLoadouts.length > 0 ||
    input.partModel !== undefined;
  if (!hasCatalogue) return undefined;

  return {
    components: input.shipComponents,
    plants: input.propulsionPlants,
    hullForms: input.shipHullForms,
    balance: input.shipBalance,
    navalProfiles: input.navalProfiles,
    armament: {
      gunFamilies: input.gunFamilies,
      gunModels: input.gunModels,
      gunMounts: input.gunMounts,
      ammunition: input.ammunition,
    },
    referenceDesigns: input.referenceDesigns,
    // Present only with part-model content, so a pack without it keeps its body hash.
    ...(input.partModel !== undefined ? { partModel: input.partModel } : {}),
    ...(input.designLoadouts.length > 0 ? { designLoadouts: input.designLoadouts } : {}),
  };
}

/**
 * Builds the campaign-file collections section of the bundle, or `undefined`
 * when the input carried no campaign content (a content-pack-only build), so
 * `canonicalSerialize(bundle)` stays backwards-compatible. The runtime
 * `CampaignCompiler` consumes these decoded collections (ticket 07).
 */
function buildCampaignCollections(input: NormalizeOutput): CampaignCollections | undefined {
  const hasCampaign =
    input.fleets.length > 0 ||
    input.economies.length > 0 ||
    input.constructions.length > 0 ||
    input.diplomacy.length > 0 ||
    input.research.length > 0 ||
    input.designs.length > 0;
  if (!hasCampaign) return undefined;

  return {
    fleets: input.fleets,
    economies: input.economies,
    constructions: input.constructions,
    diplomacy: input.diplomacy,
    research: input.research,
    designs: input.designs,
  };
}
