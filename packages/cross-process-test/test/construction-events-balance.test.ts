import { readFileSync, writeFileSync } from "node:fs";

import { CONSTRUCTION_EVENT_STREAM_FAMILY } from "@bluewave/phase-engine";
import { describe, expect, it } from "vite-plus/test";

import { executeScenario } from "../src/replay-corpus/index.js";

const MONTHS = 60;
const SEED = "construction-events-balance";
const REPORT = new URL("../../../docs/research/p6-construction-events.md", import.meta.url);

interface CauseTally {
  delays: number;
  delayMonths: number;
  overruns: number;
  overrunWork: number;
}

function measure() {
  const causes = new Map<string, CauseTally>();
  const tally = (code: string): CauseTally => {
    const found = causes.get(code);
    if (found !== undefined) return found;
    const fresh = { delays: 0, delayMonths: 0, overruns: 0, overrunWork: 0 };
    causes.set(code, fresh);
    return fresh;
  };
  let projectMonths = 0;
  const hit = new Set<string>();
  const heldMonths = new Map<string, number>();
  const deliveredIds: string[] = [];
  for (const executed of executeScenario({
    id: "construction-events-balance",
    seed: SEED,
    months: MONTHS,
  })) {
    const drawn = executed.result.randomLedger.all.filter(
      (d) => d.streamId === CONSTRUCTION_EVENT_STREAM_FAMILY,
    );
    projectMonths += new Set(drawn.map((d) => d.entityKey)).size;
    for (const d of drawn) {
      if (d.outcome === "DELAYED") {
        tally(d.reasonCode ?? "").delays += 1;
        hit.add(d.entityKey);
      } else if (d.outcome === "DELAY_MONTHS") {
        tally(d.reasonCode ?? "").delayMonths += d.draw;
        heldMonths.set(d.entityKey, (heldMonths.get(d.entityKey) ?? 0) + d.draw);
      } else if (d.outcome === "OVERRUN") {
        tally(d.reasonCode ?? "").overruns += 1;
        hit.add(d.entityKey);
      }
    }
    for (const event of executed.result.eventLedger.all) {
      if (event.body.kind === "ConstructionOverrun")
        tally(event.body.reason).overrunWork += Number(event.body.amount);
      if (event.body.kind === "ShipDelivered") deliveredIds.push(event.body.projectId);
    }
  }
  return { causes, projectMonths, hit, heldMonths, deliveredIds };
}

const perHundred = (count: number, projectMonths: number): string =>
  projectMonths === 0 ? "0.00" : ((count * 100) / projectMonths).toFixed(2);

const percent = (part: number, whole: number): string =>
  whole === 0 ? "n/a" : `${((part * 100) / whole).toFixed(1)}%`;

function buildReport(): string {
  const { causes, projectMonths, hit, heldMonths, deliveredIds } = measure();
  const late = deliveredIds.filter((id) => (heldMonths.get(id) ?? 0) > 0).length;
  const costHit = deliveredIds.filter((id) => hit.has(id)).length;
  const rows = [...causes.entries()]
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(
      ([code, t]) =>
        `| ${code} | ${t.delays} | ${t.delayMonths} | ${t.overruns} | ${t.overrunWork} |`,
    );
  const delays = [...causes.values()].reduce((sum, t) => sum + t.delays, 0);
  const overruns = [...causes.values()].reduce((sum, t) => sum + t.overruns, 0);
  return [
    "# Construction events (generated)",
    "",
    "Generated by `packages/cross-process-test/test/construction-events-balance.test.ts`; do not edit by hand.",
    "",
    `Passive run: production 1880 start state, no commands, seed \`${SEED}\`, ${MONTHS} months, every nation. Rows are PROVISIONAL (\`content/production/1880/construction-events.ts\`).`,
    "",
    "A project-month is one home-built ship or rebuild that was ACTIVE or ACCELERATED when the month's draw ran.",
    "",
    `- Project-months drawn: ${projectMonths}`,
    `- Delays: ${delays} (${perHundred(delays, projectMonths)} per hundred project-months)`,
    `- Overruns: ${overruns} (${perHundred(overruns, projectMonths)} per hundred project-months)`,
    `- Ships delivered: ${deliveredIds.length}`,
    `- Late at delivery (held by at least one delay; a hold slips delivery by exactly its months): ${late} of ${deliveredIds.length} (${percent(late, deliveredIds.length)})`,
    `- Delivered after any event hit (delay or overrun): ${costHit} of ${deliveredIds.length} (${percent(costHit, deliveredIds.length)})`,
    "",
    "| Cause | Delays | Months held | Overruns | Work added |",
    "| --- | --- | --- | --- | --- |",
    ...rows,
    "",
  ].join("\n");
}

describe("construction events balance report", () => {
  it("matches the generated report", () => {
    const report = buildReport();
    if (process.env["CONSTRUCTION_EVENTS_REPORT_WRITE"] === "1") writeFileSync(REPORT, report);
    expect(readFileSync(REPORT, "utf8")).toBe(report);
  });
});
