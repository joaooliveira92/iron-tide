import { readFileSync, writeFileSync } from "node:fs";

import { describe, expect, it } from "vite-plus/test";

import { runEventCatalogue, type EventRun } from "../src/event-catalogue-run.js";

const MONTHS = 240;
const SEED_COUNT = 4;
const SEED_PREFIX = "event-catalogue-balance";
const SEEDS = Array.from({ length: SEED_COUNT }, (_, i) => `${SEED_PREFIX}-${i + 1}`);
const REPORT = new URL("../../../docs/research/p7-event-catalogue.md", import.meta.url);
const MIN_FIRED_PER_NATION_DECADE = 0.5;
const MAX_FIRED_PER_NATION_DECADE = 6;

const decadeOf = (month: string): number => Math.floor(Number(month.slice(0, 4)) / 10) * 10;

const mean = (total: number): string => (total / SEED_COUNT).toFixed(2);

function buildReport(runs: readonly EventRun[]): string {
  const first = runs[0]!;
  const nations = first.nationIds;
  const decades = [...new Set(runs.flatMap((run) => run.fired.map((f) => decadeOf(f.month))))].sort(
    (a, b) => a - b,
  );
  const cell = new Map<string, number>();
  const perEvent = new Map<string, { total: number; ai: number; fallback: number }>();
  for (const run of runs) {
    for (const f of run.fired) {
      const key = `${f.nationId}/${decadeOf(f.month)}`;
      cell.set(key, (cell.get(key) ?? 0) + 1);
      const row = perEvent.get(f.eventId) ?? { total: 0, ai: 0, fallback: 0 };
      row.total += 1;
      if (f.resolvedBy === "AI") row.ai += 1;
      if (f.resolvedBy === "DEFAULT") row.fallback += 1;
      perEvent.set(f.eventId, row);
    }
  }
  const nationRows = nations.map((nation) => {
    const counts = decades.map((decade) => cell.get(`${nation}/${decade}`) ?? 0);
    return `| ${nation} | ${counts.map(mean).join(" | ")} |`;
  });
  const totals = decades.map((decade) =>
    nations.reduce((sum, nation) => sum + (cell.get(`${nation}/${decade}`) ?? 0), 0),
  );
  const eventRows = [...perEvent.entries()]
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([id, row]) => `| ${id} | ${mean(row.total)} | ${row.ai} | ${row.fallback} |`);
  const maxAge = Math.max(...runs.flatMap((run) => run.months.map((m) => m.oldestPendingAge)));
  return [
    "# 1880 event catalogue (generated)",
    "",
    "Generated by `packages/cross-process-test/test/event-catalogue-balance.test.ts`; do not edit by hand.",
    "",
    `Unattended run: production 1880 start state, no commands, player nation \`uk\` never answers (its dilemmas lapse to the default), ${SEED_COUNT} seeds \`${SEED_PREFIX}-1\` to \`${SEED_PREFIX}-${SEED_COUNT}\`, ${MONTHS} months each, ${nations.length} nations, ${first.catalogueSize} events. All weights, cooldowns and deltas are PROVISIONAL (\`content/production/1880/events/\`).`,
    "",
    `- Events fired, mean per seed: ${decades.map((d, i) => `${d}s ${mean(totals[i]!)}`).join(", ")}`,
    `- Oldest pending dilemma at any month end: ${maxAge} months`,
    `- Runs ended early by the designed prestige sacking of the passive player: ${runs.filter((run) => run.careerEndedMonth !== null).length} of ${SEED_COUNT}`,
    "",
    "## Events fired per nation per decade (mean per seed)",
    "",
    `| Nation | ${decades.map((d) => `${d}s`).join(" | ")} |`,
    `| --- | ${decades.map(() => "---").join(" | ")} |`,
    ...nationRows,
    "",
    "## Events fired per event (mean per seed)",
    "",
    "| Event | Mean per seed | Resolved by AI | Resolved by default |",
    "| --- | --- | --- | --- |",
    ...eventRows,
    "",
  ].join("\n");
}

describe("1880 event catalogue balance report", () => {
  it("fires every event and every nation each decade, and matches the committed report", () => {
    const runs = SEEDS.map((seed) => runEventCatalogue(seed, MONTHS));
    for (const run of runs) {
      const expectedMonths = run.careerEndedMonth === null ? MONTHS : run.careerEndedMonth - 1;
      expect(run.months).toHaveLength(expectedMonths);
    }
    const first = runs[0]!;
    const firedIds = new Set(runs.flatMap((run) => run.fired.map((f) => f.eventId)));
    expect(firedIds.size, "every catalogue event fires at least once").toBe(first.catalogueSize);
    const decades = [...new Set(runs.flatMap((r) => r.fired.map((f) => decadeOf(f.month))))];
    for (const nation of first.nationIds) {
      for (const decade of decades) {
        const total = runs.reduce(
          (sum, run) =>
            sum +
            run.fired.filter((f) => f.nationId === nation && decadeOf(f.month) === decade).length,
          0,
        );
        const perSeed = total / SEED_COUNT;
        expect(perSeed, `${nation} ${decade}s`).toBeGreaterThanOrEqual(MIN_FIRED_PER_NATION_DECADE);
        expect(perSeed, `${nation} ${decade}s`).toBeLessThanOrEqual(MAX_FIRED_PER_NATION_DECADE);
      }
    }
    const report = buildReport(runs);
    if (process.env["EVENT_CATALOGUE_REPORT_WRITE"] === "1") {
      writeFileSync(REPORT, report);
      return;
    }
    expect(readFileSync(REPORT, "utf8")).toBe(report);
  }, 600_000);
});
