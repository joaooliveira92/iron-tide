import { readFileSync, writeFileSync } from "node:fs";

import { decidePeaceProposal, decidePeaceResponse } from "@bluewave/ai";
import { peaceBehaviourFromRulesets } from "@bluewave/content-compiler";
import { describe, expect, it } from "vite-plus/test";

import { compileProductionCampaign } from "../src/production-pack.js";

const REPORT = new URL("../../../docs/research/p5-peace-behaviour.md", import.meta.url);

function productionRules() {
  const decoded = peaceBehaviourFromRulesets(compileProductionCampaign().bundle.rulesets);
  if (decoded === undefined || !decoded.ok)
    throw new Error("production ruleset has no valid peaceBehaviour section");
  return decoded.value;
}

const rules = productionRules();
const margin = rules.acceptanceScoreMargin;

function fixtureSnapshot(attackerWarScore: number, defenderWarScore: number) {
  return {
    wars: {
      wars: [
        {
          id: "w1",
          attackerId: "a",
          defenderId: "d",
          attackerWarScore,
          defenderWarScore,
          status: "ACTIVE",
        },
      ],
    },
    world: {
      areas: [
        { id: "home", controller: "d", cessionCost: 5 },
        { id: "far", controller: "d", cessionCost: 30 },
        { id: "near", controller: "d", cessionCost: 10 },
        { id: "unpriced", controller: "d" },
      ],
      possessions: [],
    },
    nations: new Map([["d", { homeAreaId: "home" }]]),
  } as any;
}

function fixtureRows(): string[] {
  return [-40, -20, -19, 0, 19, 20, 40].map((lead) => {
    const s = fixtureSnapshot(Math.max(lead, 0), Math.max(-lead, 0));
    const proposal = decidePeaceProposal(s, "w1", "a", margin);
    const cession = decidePeaceResponse(s, "w1", "d", { _tag: "CedeArea", areaId: "far" }, margin);
    const status = decidePeaceResponse(s, "w1", "d", { _tag: "StatusQuo" }, margin);
    return `| ${lead} | ${proposal.term?._tag ?? "none"} (${proposal.reason}) | ${cession.accept ? "accept" : "refuse"} | ${status.accept ? "accept" : "refuse"} |`;
  });
}

function productionSection(): string[] {
  const { state, bundle } = compileProductionCampaign();
  const areas = state.snapshot.world.areas;
  const priced = areas.filter((a) => a.cessionCost !== undefined);
  const provenance = new Map(bundle.areas.map((a) => [a.id, a.provenance?.sourceStatus]));
  const loserId = areas.find((a) => a.controller !== undefined)?.controller ?? "";
  const probe = {
    wars: {
      wars: [
        {
          id: "probe",
          attackerId: "probe-attacker",
          defenderId: loserId,
          attackerWarScore: margin * 2,
          defenderWarScore: 0,
          status: "ACTIVE",
        },
      ],
    },
    world: state.snapshot.world,
    nations: state.snapshot.nations,
  } as any;
  const probeDecision = decidePeaceProposal(probe, "probe", "probe-attacker", margin);
  const lines = [
    "## Production cede costs",
    "",
    "Derived from the compiled 1880 pack (`content/production/1880`).",
    "",
    `- Areas: ${areas.length}`,
    `- Areas with an authored \`cessionCost\`: ${priced.length}`,
  ];
  if (priced.length === 0) {
    lines.push(
      "- No cede cost is sourced for the production pack: every value is PROVISIONAL and none is authored.",
    );
  } else {
    lines.push(
      "- Authored values (all PROVISIONAL unless the provenance status says otherwise):",
      "",
    );
    lines.push("| Area | cessionCost | Provenance status |", "| --- | --- | --- |");
    for (const a of priced) {
      lines.push(
        `| ${a.id} | ${a.cessionCost} | ${provenance.get(a.id) ?? "none (PROVISIONAL)"} |`,
      );
    }
    lines.push("");
  }
  lines.push(
    `- Proposer leading by ${margin * 2} against the controller of \`${loserId}\` on production areas: ${probeDecision.term?._tag ?? "none"} (${probeDecision.reason}).`,
    "- Consumer: the monthly diplomacy phase (#777) raises StatusQuo offers to the player; no area is priced, so no CedeArea offer arises.",
    "",
  );
  return lines;
}

describe("peace behaviour balance report", () => {
  it("matches the generated report", () => {
    const report = [
      "# Peace behaviour (generated)",
      "",
      "Generated by `packages/cross-process-test/test/peace-behaviour-balance.test.ts`; do not edit by hand.",
      "",
      `Acceptance score margin: ${margin} (PROVISIONAL, unsourced; authored in the \`peaceBehaviour\` section of \`content/production/1880/rulesets.ts\`).`,
      "",
      `Proposal chance once a side leads by the margin: ${rules.proposalChanceBp} basis points a month (PROVISIONAL balance target).`,
      "",
      "Proposer (attacker) lead over the defender, fixture areas priced 10 and 30, home area 5 (protected).",
      "",
      "| Proposer lead | Proposal | Defender on CedeArea | Defender on StatusQuo |",
      "| --- | --- | --- | --- |",
      ...fixtureRows(),
      "",
      ...productionSection(),
    ].join("\n");
    if (process.env["PEACE_REPORT_WRITE"] === "1") writeFileSync(REPORT, report);
    expect(readFileSync(REPORT, "utf8")).toBe(report);
  });

  it("names the production pack as unpriced", () => {
    expect(readFileSync(REPORT, "utf8")).toContain("## Production cede costs");
  });
});
