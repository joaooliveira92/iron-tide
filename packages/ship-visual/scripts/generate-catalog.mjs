#!/usr/bin/env node
// Generate `src/catalog.generated.ts` from `content/ship-visual/parts.yaml` (ADR-0148).
//
// The YAML is decoded through `ShipVisualCatalogSchema` (strict, provenance required) from the BUILT
// `@bluewave/content-schema`, so build it first:
//
//   pnpm --filter @bluewave/content-schema build && pnpm --filter @bluewave/ship-visual catalog:generate
//
// The output is a typed constant, so the renderer never parses YAML or bundles Effect (ADR-0105/0125).
// `test/catalog-sync.test.ts` fails when the committed module and the YAML differ.

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { execFileSync } from "node:child_process";
import { decodeStrict, parseYamlSafe, ShipVisualCatalogSchema } from "@bluewave/content-schema";
import { DiagnosticCollector } from "@bluewave/diagnostics";

const PKG = resolve(import.meta.dirname, "..");
const SOURCE = resolve(PKG, "../../content/ship-visual/parts.yaml");
const TARGET = resolve(PKG, "src/catalog.generated.ts");

// The hardened parser (size, nesting and alias caps; no executable tags), as for every authored content file.
const diagnostics = new DiagnosticCollector();
const parsed = parseYamlSafe(readFileSync(SOURCE, "utf8"), SOURCE, diagnostics);
if (!parsed.success) throw new Error(diagnostics.toHuman());
const catalog = decodeStrict(ShipVisualCatalogSchema, parsed.data);

const header = `// GENERATED by scripts/generate-catalog.mjs from content/ship-visual/parts.yaml. Do not edit by hand.
import type { PartCatalog } from "./catalog.js";

`;
writeFileSync(
  TARGET,
  `${header}export const PART_CATALOG: PartCatalog = ${JSON.stringify(catalog, null, 2)};\n`,
);
execFileSync("pnpm", ["exec", "vp", "fmt", "--write", TARGET], { cwd: PKG, stdio: "inherit" });
console.log(
  `catalog:generate: ${catalog.mounts.length} mount(s), ${catalog.masts.length} mast(s) -> src/catalog.generated.ts`,
);
